def render_figures(rep: Mapping[str, Any], out: Path) -> list[str]:
    import matplotlib.pyplot as plt
    out.mkdir(parents=True, exist_ok=True)
    names = []
    for name, fig in build_figures(rep).items():
        fig.savefig(out / f"{name}.pdf")
        plt.close(fig)
        names.append(f"{name}.pdf")
    return names


