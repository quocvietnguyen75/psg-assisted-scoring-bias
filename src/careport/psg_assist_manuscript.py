def _nominal_kappa(a: Sequence[str], b: Sequence[str]) -> float:
    """Unweighted Cohen's kappa; 1 when both series are constant and equal."""
    n = len(a)
    po = sum(x == y for x, y in zip(a, b)) / n
    counts_a: dict[str, int] = {}
    counts_b: dict[str, int] = {}
    for x in a:
        counts_a[x] = counts_a.get(x, 0) + 1
    for y in b:
        counts_b[y] = counts_b.get(y, 0) + 1
    pe = sum(counts_a.get(k, 0) * counts_b.get(k, 0) for k in set(counts_a) | set(counts_b)) / (n * n)
    return 1.0 if pe >= 1 else (po - pe) / (1 - pe)


def _d1_values(v: dict[str, str], codes: Sequence[Mapping[str, str]], devices: Sequence[Mapping[str, str]]) -> None:
    """Amendment 005 D1: each blind coder's agreement with the first coding (overall, on the summaries the coder was
    blind for, and on those they had checked in the first round), the inter-coder agreement, the disagreements and
    the adjudicated changes (the adjudicated codes are the current DEVICES.csv)."""
    current = {d["k_number"]: d for d in devices}
    agree_all: list[int] = []
    kappa_all: list[float] = []
    for short, tag, _ in D1_CODERS:
        for fshort, field, _ in D1_FIELDS:
            rows = [r for r in codes if r["field"] == field]
            for subset in ("all", "blind", "seen"):
                sel = [r for r in rows if subset == "all" or r[f"{tag}_exposure"] == subset]
                first = [r["first_round_code"] for r in sel]
                coded = [r[f"{tag}_code"] for r in sel]
                n_agree = sum(x == y for x, y in zip(first, coded))
                kappa = _nominal_kappa(first, coded)
                v[f"d1-{short}-{fshort}-{subset}-agree"] = f"{n_agree}/{len(sel)}"
                v[f"d1-{short}-{fshort}-{subset}-kappa"] = f"{kappa:.3f}"
                if subset == "all":
                    agree_all.append(n_agree)
                    kappa_all.append(kappa)
    v["d1-agree-min"], v["d1-agree-max"] = str(min(agree_all)), str(max(agree_all))
    v["d1-kappa-min"], v["d1-kappa-max"] = f"{min(kappa_all):.3f}", f"{max(kappa_all):.3f}"
    # The blind-only agreement range for the Results, in prose form ("8 of 10"): the lowest and highest fraction over
    # the six coder-by-field cells, each over the summaries for which that coder was blind.
    blind_cells: list[tuple[float, int, int]] = []
    for short, tag, _ in D1_CODERS:
        for fshort, field, _ in D1_FIELDS:
            n_agree, n_blind = (int(x) for x in v[f"d1-{short}-{fshort}-blind-agree"].split("/"))
            blind_cells.append((n_agree / n_blind, n_agree, n_blind))
    lo, hi = min(blind_cells), max(blind_cells)
    v["d1-blind-agree-min"], v["d1-blind-agree-max"] = f"{lo[1]} of {lo[2]}", f"{hi[1]} of {hi[2]}"
    for fshort, field, _ in D1_FIELDS:
        rows = [r for r in codes if r["field"] == field]
        a, b = [r["PTD_code"] for r in rows], [r["DHAN_code"] for r in rows]
        v[f"d1-inter-{fshort}-agree"] = f"{sum(x == y for x, y in zip(a, b))}/{len(rows)}"
        v[f"d1-inter-{fshort}-kappa"] = f"{_nominal_kappa(a, b):.3f}"
    disagree = [r for r in codes if any(r[f"{tag}_code"] != r["first_round_code"] for _, tag, _ in D1_CODERS)]
    v["d1-disagreements"] = str(len(disagree))
    v["d1-disagree-summaries"] = str(len({r["k_number"] for r in disagree}))
    v["d1-both-disagree"] = str(sum(all(r[f"{tag}_code"] != r["first_round_code"] for _, tag, _ in D1_CODERS)
                                    for r in disagree))
    v["d1-changed"] = str(sum(current[r["k_number"]][r["field"]] != r["first_round_code"] for r in disagree))
    ref_rows = [r for r in codes if r["field"] == "reference_type"]
    v["d1-first-routine"] = str(sum(r["first_round_code"] == "routine_clinical_scoring" for r in ref_rows))
    v["d1-first-notdesc"] = str(sum(r["first_round_code"] == "not_described" for r in ref_rows))


def _is_difference(target: str) -> bool:
    """Validation targets that are differences get a sign; levels (M3 agreement, shares) do not."""
    return not target.startswith(("V4", "V7", "V8"))


