def exploratory_consistency(params: Mapping[str, Any], alpha: float = 0.22, consistency: float = 0.5,
                            n: int = 12, full: int = 7, loo: int = 6, strong: int = 10,
                            bins: Sequence[Sequence[int]] = ((12, 12), (10, 11), (8, 9), (0, 7))) -> dict[str, Any]:
    """Exploratory (not pre-specified) model configuration matching the consensus-level observations.

    Amendment 006 B adds its anchoring value (M1), its assisted-reference bias with 1 and 25 experts and its
    validation targets (the arguments mirror the frozen configuration of amendment 003).
    """
    from careport.psg_assist_remedy import _decide, _session_pairs, joint_counts
    from careport.psg_assist_simulation import Model, _prefill, compare_references, difficulty_nodes, model_targets

    model = replace(Model(**{**params, "alphas": None}), alpha=alpha, consistency=consistency)
    both = changed = toward = a_rs = rm_rs = 0.0
    for w, b in difficulty_nodes(model):
        a = _prefill(model, b)
        for correct, pst in ((True, a), (False, 1 - a)):
            dist = joint_counts(_session_pairs(model, n, b, correct))
            for km in range(n + 1):
                rm = _decide(km, n, full)
                if rm is None:
                    continue
                for ks in range(n + 1):
                    rs = _decide(ks, n, full)
                    if rs is None:
                        continue
                    wt = w * pst * dist[km][ks]
                    both += wt
                    a_rs += wt * (correct == rs)
                    rm_rs += wt * (rm == rs)
                    if rm != rs:
                        changed += wt
                        toward += wt * (rs == correct)
    ref = compare_references(model, n, "majority")
    return {"alpha": alpha, "consistency": consistency, "side_taking": toward / changed,
            "prefill_vs_assisted": a_rs / both, "manual_vs_assisted": rm_rs / both,
            "delta_auto": ref["signatures"]["delta_auto"], "bias_assisted": ref["assisted"]["bias_a"],
            "breakeven_assisted": ref["assisted"]["breakeven"],
            "reference_accuracy_assisted": ref["assisted"]["reference_accuracy"],
            "m1": ref["signatures"]["M1"],
            "bias_n1": compare_references(model, 1, "majority")["assisted"]["bias_a"],
            "bias_n25": compare_references(model, 25, "majority")["assisted"]["bias_a"],
            "validation": _flat_targets(model_targets(model, n, full, loo, strong, [list(b) for b in bins]))}


def _flat_targets(targets: Mapping[str, Any]) -> dict[str, float | None]:
    """V1 to V10 of a model_targets() result with the nested V4 and V5 dictionaries flattened as 'V4:agree_manual'."""
    out: dict[str, float | None] = {}
    for key in ("V1", "V2", "V3", "V6", "V7", "V8", "V9", "V10"):
        out[key] = targets[key]
    for sub, val in targets["V4"].items():
        out[f"V4:{sub}"] = val
    for sub, val in targets["V5"].items():
        out[f"V5:{sub}"] = val
    return out


