def _table(caption: str, label: str, spec: str, header: Sequence[str], rows: Sequence[Sequence[str]],
           note: str = "", size: str = "\\small") -> str:
    head = [f"\\makecell{{{h}}}" if "\\\\" in h else h for h in header]
    lines = ["\\begin{table}[tbp]", "\\centering", size, f"\\caption{{{caption}}}", f"\\label{{{label}}}",
             "\\begin{adjustbox}{max width=\\linewidth}", f"\\begin{{tabular}}{{{spec}}}", "\\toprule",
             " & ".join(head) + " \\\\", "\\midrule"]
    lines += [" & ".join(r) + " \\\\" for r in rows]
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{adjustbox}"]
    if note:
        lines += ["\\par\\smallskip", f"\\begin{{minipage}}{{0.95\\linewidth}}\\footnotesize {note}\\end{{minipage}}"]
    lines.append("\\end{table}")
    return "\n".join(lines) + "\n"


def _mc(top: str, bottom: str) -> str:
    """A two-line table cell."""
    return f"\\makecell{{{top}\\\\{bottom}}}"


