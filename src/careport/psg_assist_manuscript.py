def fmt(x: float, nd: int = 3, signed: bool = False) -> str:
    """Fixed decimals; a LaTeX minus for negatives. A value that rounds to zero prints unsigned.

    \\ensuremath keeps the result valid in both text and math mode.
    """
    body = f"{abs(x):.{nd}f}"
    if float(body) == 0:
        return body
    return ("\\ensuremath{-}" if x < 0 else "+" if signed else "") + body


def fmt_int(n: int) -> str:
    return f"{int(n):,}".replace(",", "{,}")


def fmt_pct(x: float, nd: int = 0) -> str:
    return f"{100 * x:.{nd}f}\\%"


def fmt_p(p: float) -> str:
    if p < 0.001:
        exp = math.floor(math.log10(p))
        mant = p / 10 ** exp
        if round(mant, 1) >= 10:
            mant, exp = mant / 10, exp + 1
        return f"\\ensuremath{{{mant:.1f}\\times10^{{{exp}}}}}"
    return f"{p:.3f}" if p < 0.01 else f"{p:.2f}"


def _betacf(a: float, b: float, x: float) -> float:
    """Continued fraction for the regularized incomplete beta function (modified Lentz)."""
    tiny, qab, qap, qam = 1e-300, a + b, a + 1.0, a - 1.0
    c, d = 1.0, 1.0 - qab * x / qap
    d = 1.0 / (d if abs(d) > tiny else tiny)
    h = d
    for m in range(1, 400):
        m2 = 2 * m
        aa = m * (b - m) * x / ((qam + m2) * (a + m2))
        d = 1.0 + aa * d
        d = 1.0 / (d if abs(d) > tiny else tiny)
        c = 1.0 + aa / (c if abs(c) > tiny else tiny)
        h *= d * c
        aa = -(a + m) * (qab + m) * x / ((a + m2) * (qap + m2))
        d = 1.0 + aa * d
        d = 1.0 / (d if abs(d) > tiny else tiny)
        c = 1.0 + aa / (c if abs(c) > tiny else tiny)
        delta = d * c
        h *= delta
        if abs(delta - 1.0) < 3e-16:
            break
    return h


def _betainc(a: float, b: float, x: float) -> float:
    """Regularized incomplete beta function I_x(a, b)."""
    if x <= 0.0:
        return 0.0
    if x >= 1.0:
        return 1.0
    front = math.exp(math.lgamma(a + b) - math.lgamma(a) - math.lgamma(b) + a * math.log(x) + b * math.log(1.0 - x))
    if x < (a + 1.0) / (a + b + 2.0):
        return front * _betacf(a, b, x) / a
    return 1.0 - front * _betacf(b, a, 1.0 - x) / b


def t_quantile(p: float, df: int) -> float:
    """Quantile of Student's t distribution (p > 0.5), by bisection on the exact distribution function."""
    def cdf(t: float) -> float:
        return 1.0 - 0.5 * _betainc(df / 2.0, 0.5, df / (df + t * t))
    lo, hi = 0.0, 1000.0
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if cdf(mid) < p:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def write_values(values: Mapping[str, str], path: Path) -> None:
    lines = ["% Generated by careport.psg_assist_manuscript from the committed reports; do not edit."]
    for key in sorted(values):
        if not _KEY.match(key):
            raise ValueError(f"invalid value key: {key!r}")
        lines.append(f"\\expandafter\\def\\csname val@{key}\\endcsname{{{values[key]}}}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def used_keys(text: str) -> set[str]:
    return set(re.findall(r"\\val\{([^}]+)\}", text))


MANUSCRIPT_FILES = ("main.tex", "supplement.tex")


def missing_value_keys(folder: Path, values: Mapping[str, str]) -> dict[str, list[str]]:
    """Keys used by each manuscript file in the folder that have no generated value."""
    out = {}
    for name in MANUSCRIPT_FILES:
        path = folder / name
        if path.is_file():
            missing = sorted(used_keys(path.read_text(encoding="utf-8")) - set(values))
            if missing:
                out[name] = missing
    return out


def _braced(text: str, start: int) -> tuple[str, int]:
    """Content of the balanced {...} group opening at text[start], and the index just after it."""
    if text[start:start + 1] != "{":
        raise ValueError(f"expected '{{' at position {start}")
    depth = 0
    for i in range(start, len(text)):
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        if depth == 0:
            return text[start + 1:i], i + 1
    raise ValueError("unbalanced braces")


def supplement_refs(aux: str, target: str = "supplement.pdf") -> str:
    """The supplement's labels as \\newlabel lines for main.tex, each linking to the supplement's PDF.

    This is what xr-hyper does when it reads supplement.aux. Writing it to a file lets main.tex compile on its own,
    as on Overleaf or a journal's system, without compiling the supplement first.
    """
    lines = ["% Generated by careport.psg_assist_manuscript from supplement.aux; do not edit.", "\\makeatletter"]
    for match in re.finditer(r"^\\newlabel\{([^}]*)\}", aux, flags=re.M):
        body, pos, fields = _braced(aux, match.end())[0], 0, []
        while pos < len(body):
            field, pos = _braced(body, pos)
            fields.append(field)
        if len(fields) != 5:
            raise ValueError(f"label {match.group(1)!r} has {len(fields)} fields, not hyperref's 5")
        fields[4] = target
        lines.append(f"\\newlabel{{{match.group(1)}}}{{" + "".join(f"{{{f}}}" for f in fields) + "}")
    lines.append("\\makeatother")
    return "\n".join(lines) + "\n"


