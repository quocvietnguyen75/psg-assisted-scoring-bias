def _ci(v: dict[str, str], key: str, ci: Sequence[float], nd: int = 3, signed: bool = False) -> None:
    v[f"{key}-lo"], v[f"{key}-hi"] = fmt(ci[0], nd, signed), fmt(ci[1], nd, signed)


